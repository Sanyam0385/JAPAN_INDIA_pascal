// Key parity validation function
function flattenKeys(obj, prefix = '') {
  let keys = [];
  for (const k of Object.keys(obj)) {
    const nextKey = prefix ? `${prefix}.${k}` : k;
    if (typeof obj[k] === 'object' && obj[k] !== null && !Array.isArray(obj[k])) {
      keys = keys.concat(flattenKeys(obj[k], nextKey));
    } else {
      keys.push(nextKey);
    }
  }
  return keys;
}

const enKeys = flattenKeys(en).sort();
const hiKeys = flattenKeys(hi).sort();
const paKeys = flattenKeys(pa).sort();
const jaKeys = flattenKeys(ja).sort();

console.log(`[Locales Build] en: ${enKeys.length} keys`);
console.log(`[Locales Build] hi: ${hiKeys.length} keys`);
console.log(`[Locales Build] pa: ${paKeys.length} keys`);
console.log(`[Locales Build] ja: ${jaKeys.length} keys`);

function checkDiff(targetName, targetKeys) {
  const missing = enKeys.filter(k => !targetKeys.includes(k));
  const extra = targetKeys.filter(k => !enKeys.includes(k));
  if (missing.length > 0) {
    console.error(`[Error] ${targetName} is missing ${missing.length} keys:`, missing.slice(0, 10));
    return false;
  }
  if (extra.length > 0) {
    console.warn(`[Warn] ${targetName} has ${extra.length} extra keys:`, extra.slice(0, 10));
  }
  return true;
}

const okHi = checkDiff('hi', hiKeys);
const okPa = checkDiff('pa', paKeys);
const okJa = checkDiff('ja', jaKeys);

if (!okHi || !okPa || !okJa) {
  console.error('Key parity check failed! Please fix missing keys.');
  process.exit(1);
}

